// Writes public/zh-cn-chars.js: the Traditional -> Simplified character table and
// OpenCC's character-exception phrases, taken from OpenCC's own reviewed data
// (TSCharacters, TWVariantsRev, TSPhrases; Apache-2.0, notice in
// public/zh-cn-chars-LICENSE.txt). Studio's Taiwan -> Mainland term list and the
// zh-CN overrides are not generated: they live in public/zh-cn-terms.js.
//   OPENCC_DICT=<opencc-js>/dist/esm-lib/dict bun scripts/gen-zh-cn-chars.ts
import { writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = process.env.OPENCC_DICT;
if (!dir) { console.error("set OPENCC_DICT to opencc-js's dist/esm-lib/dict"); process.exit(2); }
const load = async (name: string): Promise<[string, string][]> =>
  String((await import(join(dir, `${name}.js`))).default).split("|").map((e) => e.split(" ")).map(([k, v]) => [k, v]);
const ts = new Map(await load("TSCharacters"));
const chars = new Map(ts);
// Taiwan variant forms (e.g. 為, 群) first become OpenCC's standard Traditional, then Simplified
for (const [k, v] of await load("TWVariantsRev")) if ([...k].length === 1) chars.set(k, [...v].map((c) => ts.get(c) ?? c).join(""));
for (const [k, v] of [...chars]) if (k === v) chars.delete(k);
const phrases = (await load("TSPhrases")).filter(([k, v]) => k !== v);
const pack = (m: Iterable<[string, string]>) => [...m].map(([k, v]) => `${k} ${v}`).join("|");
writeFileSync(join(import.meta.dir, "../public/zh-cn-chars.js"), [
  "// Generated by scripts/gen-zh-cn-chars.ts from OpenCC data (TSCharacters, TWVariantsRev, TSPhrases) — do not edit.",
  "// Copyright the OpenCC authors; Apache License 2.0, see /zh-cn-chars-LICENSE.txt. Format: \"traditional simplified|…\".",
  `window.crewZhChars = { chars: ${JSON.stringify(pack(chars))},`,
  `  phrases: ${JSON.stringify(pack(phrases))} };`, ""].join("\n"));
console.log(`zh-cn-chars: ${chars.size} characters, ${phrases.length} phrases`);

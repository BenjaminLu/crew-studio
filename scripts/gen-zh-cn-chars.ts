// Writes public/zh-cn-chars.js: the Traditional -> Simplified character table and
// phrases, taken from OpenCC's own reviewed data (Apache-2.0, notice in
// public/zh-cn-chars-LICENSE.txt and THIRD_PARTY_NOTICES.md). Studio's Taiwan ->
// Mainland term list and the zh-CN overrides are not generated: they live in
// public/zh-cn-terms.js.
//   OPENCC_DICT=<opencc-js>/dist/esm-lib/dict bun scripts/gen-zh-cn-chars.ts
//
// OpenCC's tw2s runs two stages: Taiwan variants -> OpenCC Traditional
// (TWVariantsRevPhrases, TWVariantsRev), then Traditional -> Simplified
// (TSPhrases, TSCharacters). Studio converts in one longest-match pass, so this
// script folds the stages together:
//   - characters: TWVariantsRev then TSCharacters, composed;
//   - phrases: TSPhrases, and every TWVariantsRevPhrases entry run through stage two.
// Identity phrases are kept on purpose: 乾坤 -> 乾坤 and 著名 -> 著名 exist to stop the
// character table (乾 -> 干, 著 -> 着) from touching them.
// A character that is already valid Simplified (it is the Simplified form of some
// Traditional character, e.g. 么 for 麼) is never converted, so text that is already
// Simplified passes through: 什么 never becomes 什幺.
import { writeFileSync } from "node:fs";
import { join } from "node:path";
const dir = process.env.OPENCC_DICT;
if (!dir) { console.error("set OPENCC_DICT to opencc-js's dist/esm-lib/dict"); process.exit(2); }
const load = async (name: string): Promise<[string, string][]> =>
  String((await import(join(dir, `${name}.js`))).default).split("|").map((e) => e.split(" ")).map(([k, v]) => [k, v]);
const ts = new Map(await load("TSCharacters"));
const tsPhrases = await load("TSPhrases");
const simplifiedValid = new Set([...ts.values()].flatMap((v) => [...v]));
// stage two on its own: TSPhrases longest match, then TSCharacters
const tsWords = new Map(tsPhrases); const tsLongest = Math.max(...tsPhrases.map(([k]) => [...k].length));
const stage2 = (s: string) => { const cs = [...s]; let out = "";
  for (let i = 0; i < cs.length;) { let hit = false;
    for (let n = Math.min(tsLongest, cs.length - i); n >= 2; n--) { const v = tsWords.get(cs.slice(i, i + n).join("")); if (v !== undefined) { out += v; i += n; hit = true; break; } }
    if (!hit) { const c = cs[i++]; out += ts.get(c) ?? c; } }
  return out; };
const chars = new Map(ts);
for (const [k, v] of await load("TWVariantsRev")) if ([...k].length === 1) chars.set(k, [...v].map((c) => ts.get(c) ?? c).join(""));
let skipped: string[] = [];
for (const [k, v] of [...chars]) { if (k === v) chars.delete(k); else if (simplifiedValid.has(k)) { chars.delete(k); skipped.push(k); } }
const phrases = new Map<string, string>(tsPhrases);
for (const [k, v] of await load("TWVariantsRevPhrases")) if (!phrases.has(k)) phrases.set(k, stage2(v));
const pack = (m: Iterable<[string, string]>) => [...m].map(([k, v]) => `${k} ${v}`).join("|");
writeFileSync(join(import.meta.dir, "../public/zh-cn-chars.js"), [
  "// Generated by scripts/gen-zh-cn-chars.ts from OpenCC data (TSCharacters, TSPhrases, TWVariantsRev, TWVariantsRevPhrases) — do not edit.",
  "// Copyright the OpenCC authors; Apache License 2.0, see /zh-cn-chars-LICENSE.txt. Format: \"traditional simplified|…\"; a phrase that maps to itself stops character conversion inside it.",
  `window.crewZhChars = { chars: ${JSON.stringify(pack(chars))},`,
  `  phrases: ${JSON.stringify(pack(phrases))} };`, ""].join("\n"));
console.log(`zh-cn-chars: ${chars.size} characters, ${phrases.size} phrases; left alone as already Simplified: ${skipped.join(" ")}`);

// Writes src/assets.gen.ts: every file under public/ imported as an embedded
// file, so `bun build --compile` carries the whole UI inside the binary; and
// src/bundled.gen.ts: every file under workflows/, packs/, skins/, templates/ and manual/ (the
// built-in workflows, domain packs, skins and the operating manual) and Studio's docs, embedded the same way.
//   bun scripts/gen-assets.ts
import { existsSync, readdirSync, statSync, writeFileSync } from "node:fs";
import { join, relative } from "node:path";
const root = join(import.meta.dir, ".."), pub = join(root, "public");
const walkAll = (d: string, out: string[] = []) => { for (const f of readdirSync(d).sort()) { const p = join(d, f); if (statSync(p).isDirectory()) walkAll(p, out); else if (!f.startsWith(".")) out.push(p); } return out; };
const files = walkAll(pub);
const lines = ["// Generated by scripts/gen-assets.ts — do not edit. Each public/ file, embedded in the binary.", ""];
files.forEach((f, i) => lines.push(`import a${i} from "../public/${relative(pub, f)}" with { type: "file" };`));
lines.push("", "export const ASSETS: Record<string, string> = {");
files.forEach((f, i) => lines.push(`  "/${relative(pub, f)}": a${i},`));
lines.push("};", "");
writeFileSync(join(root, "src/assets.gen.ts"), lines.join("\n"));
const bundled = ["workflows", "packs", "skins", "templates", "manual"].flatMap((d) => (existsSync(join(root, d)) ? walkAll(join(root, d)) : []))
  // Studio's own docs, so a document about Crew Studio can read them in the binary too (not research notes or retros)
  .concat(existsSync(join(root, "docs")) ? walkAll(join(root, "docs")).filter((f) => f.endsWith(".md") && /^docs\/(?:[^/]+|units\/[^/]+)$/.test(relative(root, f))) : []);
const b = ["// Generated by scripts/gen-assets.ts — do not edit. Built-in workflows, packs and skins, embedded in the binary.", ""];
bundled.forEach((f, i) => b.push(`import b${i} from "../${relative(root, f)}" with { type: "file" };`));
b.push("", "export const BUNDLED: Record<string, string> = {");
bundled.forEach((f, i) => b.push(`  "${relative(root, f)}": b${i},`));
b.push("};", "");
writeFileSync(join(root, "src/bundled.gen.ts"), b.join("\n"));
console.log(`assets: ${files.length} files, bundled: ${bundled.length} files`);
